"""Bake the OFL Inter face into small, antialiased LCD glyph atlases.

Glyphs retain 2x coverage at four bits per sample so the embedded renderer can
rotate them along the connector rings without a font engine or allocation.
"""
from pathlib import Path
import hashlib
from PIL import Image, ImageDraw, ImageFont, features as pillow_features

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/fonts/inter/Inter-opsz-wght.ttf'
TARGET = ROOT / 'firmware/Tester12VRevD/DisplayFont.h'
SCALE = 2
CHARACTERS = ''.join(chr(c) for c in range(32, 127))


def atlas(name, size, weight):
    face = ImageFont.truetype(str(SOURCE), size * SCALE)
    axes = face.get_variation_axes()
    face.set_variation_by_axes([weight if a['name'] == b'Weight' else 14 if a['name'] == b'Optical size' else a['default'] for a in axes])
    features = ['-liga', 'tnum'] if name == 'value' else ['-liga']
    data = bytearray()
    glyphs = []
    for character in CHARACTERS:
        left, top, right, bottom = face.getbbox(character, anchor='ls', features=features)
        width, height = right - left, bottom - top
        image = Image.new('L', (max(1, width), max(1, height)))
        ImageDraw.Draw(image).text((-left, -top), character, font=face, fill=255, anchor='ls', features=features)
        samples = image.get_flattened_data() if hasattr(image, 'get_flattened_data') else image.getdata()
        coverage = [round(v * 15 / 255) for v in samples] if width and height else []
        offset = len(data)
        for i in range(0, len(coverage), 2):
            data.append((coverage[i] << 4) | (coverage[i + 1] if i + 1 < len(coverage) else 0))
        advance = round(face.getlength(character, features=features) * 64 / SCALE)
        glyphs.append(f'{{{offset},{advance},{left},{top},{width},{height}}}')
    result = f'static const uint8_t {name}Coverage[]={{\n'
    result += ''.join(','.join(f'0x{x:02x}' for x in data[i:i+24]) + ',\n' for i in range(0, len(data), 24))
    result += f'}};\nstatic constexpr Glyph {name}Glyphs[]={{\n'
    result += ''.join(','.join(glyphs[i:i+5]) + ',\n' for i in range(0, len(glyphs), 5))
    kern = []
    for a in CHARACTERS:
        for b in CHARACTERS:
            adjustment = round((face.getlength(a+b, features=features)-face.getlength(a, features=features)-face.getlength(b, features=features))*64/SCALE)
            if adjustment:
                kern.append(f'{{{ord(a)},{ord(b)},{adjustment}}}')
    result += f'}};\nstatic constexpr Kerning {name}Kerning[]={{\n'
    result += ''.join(','.join(kern[i:i+6]) + ',\n' for i in range(0, len(kern), 6))
    result += f'}};\nstatic constexpr Font {name}Font={{{name}Glyphs,{name}Coverage,{name}Kerning,{len(kern)},{size}}};\n'
    return result, len(data)


def main():
    if not pillow_features.check_feature('raqm'):
        raise RuntimeError('Font generation requires Pillow with Raqm for kerning and tabular digits.')
    source_hash = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    header = f'''#pragma once
#include <cstdint>
// Generated by scripts/build_lcd_typography.py. Inter, SIL OFL 1.1.
// Font and license: assets/fonts/inter/. Source SHA256: {source_hash}
namespace tester_ui {{ namespace type {{
struct Glyph {{uint32_t offset;uint16_t advance;int8_t x,y;uint8_t w,h;}};
struct Kerning {{uint8_t a,b;int16_t adjustment;}};
struct Font {{const Glyph *glyphs;const uint8_t *coverage;const Kerning *kerning;uint16_t kernCount;uint8_t size;}};
'''
    total = 0
    for name, size, weight in [('pin', 11, 550), ('label', 11, 500), ('status', 13, 500), ('value', 24, 500)]:
        text, count = atlas(name, size, weight)
        header += text
        total += count
    header += '}} // namespace tester_ui::type\n'
    TARGET.write_text(header)
    print(f'Packed Inter glyph coverage: {total} bytes; sizes 11, 11, 13, 24 px; kerning and tabular values.')


if __name__ == '__main__':
    main()
