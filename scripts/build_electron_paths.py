"""Precompute short pin-to-pin paths and a protected drawing stencil for the LCD."""
from pathlib import Path
import heapq, json, math
from PIL import ImageFont

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT/'firmware/Tester12VRevD/ElectronPaths.h'
N = 32
geo = json.loads((ROOT/'output/geometry.json').read_text())
pins = [tuple(round(120+15*v) for v in geo['pin_centres_mm'][str(i)]) for i in range(1,13)]
font = ImageFont.truetype(str(ROOT/'assets/fonts/inter/Inter-opsz-wght.ttf'),24)
font.set_variation_by_axes([650 if a['name']==b'Weight' else 14 if a['name']==b'Optical size' else a['default'] for a in font.get_variation_axes()])


def advance(text):
    return font.getlength(text,features=['-liga'])/2


def label_rect(i):
    x,y=pins[i];text=str(i+1);angle=0
    if i<9:
        a=math.atan2(y-120,x-120);radius=math.hypot(x-120,y-120)+(22 if y>120 else 13)
        angle=a+(-math.pi/2 if y>120 else math.pi/2)
        x=120+radius*math.cos(a)-math.cos(angle)*advance(text)/2
        y=120+radius*math.sin(a)-math.sin(angle)*advance(text)/2
    else:x-=advance(text)/2;y-=8
    points=[];cursor=0
    for c in text:
        l,t,r,b=font.getbbox(c,anchor='ls',features=['-liga'])
        for u,v in [(l/2+cursor,t/2),(r/2+cursor,t/2),(l/2+cursor,b/2),(r/2+cursor,b/2)]:
            points.append((x+math.cos(angle)*u-math.sin(angle)*v,y+math.sin(angle)*u+math.cos(angle)*v))
        cursor+=advance(c)
    # Include the baked half-pixel outline and bilinear antialias fringe.
    return (min(p[0] for p in points)-2.5,min(p[1] for p in points)-2.5,
            max(p[0] for p in points)+2.5,max(p[1] for p in points)+2.5)


rects=[label_rect(i) for i in range(12)]


def in_label(x,y):
    return any(l<=x<=r and t<=y<=b for l,t,r,b in rects)


def allowed(x,y,ends=(),clearance=7.8):
    return (x-120)**2+(y-120)**2<=55**2 and not in_label(x,y) and all(
        i in ends or (x-px)**2+(y-py)**2>=clearance**2 for i,(px,py) in enumerate(pins))


def route(a,b):
    start=tuple(round(v/2)*2 for v in pins[a]);end=tuple(round(v/2)*2 for v in pins[b])
    for margin in (9.5,8.7):
        queue=[(0,0,start)];cost={start:0};prev={}
        while queue:
            _,g,p=heapq.heappop(queue)
            if g>cost[p]+1e-6:continue
            if p==end:
                points=[p]
                while p in prev:p=prev[p];points.append(p)
                points=list(reversed(points));points[0]=pins[a];points[-1]=pins[b]
                lengths=[0.]
                for p,q in zip(points,points[1:]):lengths.append(lengths[-1]+math.dist(p,q))
                result=[];j=0
                for k in range(N):
                    d=lengths[-1]*k/(N-1)
                    while j+1<len(points)-1 and lengths[j+1]<d:j+=1
                    u=(d-lengths[j])/(lengths[j+1]-lengths[j])
                    result.append(tuple(round(points[j][c]*(1-u)+points[j+1][c]*u) for c in (0,1)))
                assert result[0]==pins[a] and result[-1]==pins[b]
                for x,y in result:
                    assert all(i in (a,b) or math.dist((x,y),p)>=7.8 for i,p in enumerate(pins))
                return result
            for dx,dy in ((2,0),(-2,0),(0,2),(0,-2),(2,2),(2,-2),(-2,2),(-2,-2)):
                q=(p[0]+dx,p[1]+dy)
                if not allowed(*q,(a,b),margin) or not allowed(p[0]+dx/2,p[1]+dy/2,(a,b),margin):continue
                near=min(math.dist(q,point) for i,point in enumerate(pins) if i not in (a,b))
                ng=g+math.hypot(dx,dy)+max(0,13-near)*.15
                if ng<cost.get(q,1e9):
                    cost[q]=ng;prev[q]=p;heapq.heappush(queue,(ng+math.dist(q,end),ng,q))
    raise RuntimeError(f'No path {a+1} -> {b+1}')


def main():
    paths=[route(a,b) for a in range(12) for b in range(a+1,12)]
    mask=bytearray(128*128//8)
    for y in range(128):
        for x in range(128):
            if allowed(x+56,y+56):
                i=y*128+x;mask[i//8]|=1<<(i%8)
    h='''#pragma once
#include <cstdint>
// Generated by scripts/build_electron_paths.py. Paths are visual illustrations,
// not measurements of external wiring or current. Stencil protects pin IDs.
namespace tester_ui {
static constexpr unsigned kPathSamples=32;
struct FlowPoint {uint8_t x,y;};
static constexpr FlowPoint electronPaths[66][kPathSamples]={
'''
    h+=''.join('{'+','.join('{'+str(x)+','+str(y)+'}' for x,y in p)+'},\n' for p in paths)
    h+='};\nstatic const uint8_t electronStencil[]={\n'
    h+=''.join(','.join(f'0x{b:02x}' for b in mask[i:i+24])+',\n' for i in range(0,len(mask),24))
    h+='};\n} // namespace tester_ui\n'
    TARGET.write_text(h)
    print('Precomputed 66 pin-pair paths, 32 points each, and a 2048-byte protected stencil.')


if __name__=='__main__':main()
